#!/usr/bin/env python3
"""Build (or verify) the eval corpus under datasets/corpus/.

    python datasets/build_corpus.py            # write corpus/ and manifest.json
    python datasets/build_corpus.py --check    # verify what is committed, write nothing

`--check` is the one that matters. It re-emits every artifact from its node tree
and diffs against what is on disk, runs the structural BPMN checks, and verifies
that every `expected_diagnostics` entry is a registered SPEC-* code. A reference
artifact with a dangling flow ref is worse than no reference artifact: every
alignment score computed against it would be quietly wrong.

P2-owned. Output layout, which `scripts/run_corpus.py` reads:

    datasets/corpus/manifest.json
    datasets/corpus/<case_id>/prompt.txt
    datasets/corpus/<case_id>/reference.bpmn
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tools.bpmn import check, derive_patterns, emit  # noqa: E402
from tools.case import Case  # noqa: E402
from tools.cases import ALL_CASES  # noqa: E402
from tools.spec_codes import SPEC_CODES, unknown  # noqa: E402

CORPUS_VERSION = "1.0"
BUILT = "2026-08-03"  # bump by hand; keeps rebuilds byte-identical
ROOT = Path(__file__).resolve().parent
CORPUS = ROOT / "corpus"

PROVENANCE_NOTE = (
    "Authored by P2's agent on 2026-08-03. reverse_generated cases: the reference "
    "artifact was written first from a common process template for that domain, then "
    "described in natural language, and the description became the prompt -- so the "
    "reference is genuinely what the prompt was written from, and the prompt is "
    "unrealistically detailed. hand_written cases: the prompt was written first, "
    "deliberately under-specified, and the reference is ONE reasonable reading of it "
    "rather than ground truth. No customer data and no third-party BPMN files were "
    "used; every artifact in this corpus was generated by datasets/build_corpus.py "
    "from the node trees in datasets/tools/cases_*.py."
)


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def render(case: Case) -> tuple[str, str]:
    """Return (prompt, artifact_xml) for a case, with the artifact checked."""
    header = (
        f"{case.id} -- reference artifact for the prompt in prompt.txt. "
        f"Generated by datasets/build_corpus.py; edit datasets/tools/cases_*.py, not this file."
        + ("" if case.reference_is_ground_truth else
           " ONE reasonable reading of an under-specified prompt -- not ground truth.")
    )
    xml = emit(case.process_id, case.nodes, header=header)
    problems = check(xml)
    if problems:
        raise SystemExit(f"{case.id}: invalid reference artifact:\n  " + "\n  ".join(problems))
    return case.prompt, xml


def manifest_entry(case: Case, prompt: str, xml: str) -> dict[str, object]:
    return {
        "id": case.id,
        "title": case.title,
        "domain": case.domain,
        "provenance": case.provenance,
        "under_specified": case.under_specified,
        "reference_is_ground_truth": case.reference_is_ground_truth,
        # Read back out of the artifact, not copied from the case's declared
        # tags -- a manifest claiming coverage the corpus does not have is worse
        # than one that claims nothing. `--check` asserts declared ⊆ derived.
        "patterns": derive_patterns(xml),
        "prompt_path": f"{case.id}/prompt.txt",
        "reference_path": f"{case.id}/reference.bpmn",
        "prompt_sha256": _sha(prompt),
        "reference_sha256": _sha(xml),
        "expected_diagnostics": list(case.expected_diagnostics),
        "notes": case.notes,
    }


def build() -> dict[str, object]:
    entries = []
    rendered: dict[str, tuple[str, str]] = {}
    for case in ALL_CASES:
        prompt, xml = render(case)
        rendered[case.id] = (prompt, xml)
        entries.append(manifest_entry(case, prompt, xml))

    manifest = {
        "corpus_version": CORPUS_VERSION,
        "built": BUILT,
        "owner": "P2",
        "description": (
            "Eval corpus for workflow generation: (prompt, reference artifact) pairs. The "
            "prompt is the input under evaluation; the reference artifact is what a "
            "competent implementation of that prompt looks like."
        ),
        "provenance": PROVENANCE_NOTE,
        "rebuild": "python datasets/build_corpus.py    (verify: --check)",
        "spec_code_registry": "docs/decisions/0008-spec-sufficiency-code-registry.md",
        "counts": {
            "total": len(ALL_CASES),
            "reverse_generated": sum(1 for c in ALL_CASES if c.provenance == "reverse_generated"),
            "hand_written_underspecified": sum(1 for c in ALL_CASES if c.under_specified),
            "by_domain": dict(sorted(Counter(c.domain for c in ALL_CASES).items())),
            "by_pattern": dict(sorted(Counter(
                p for e in entries for p in e["patterns"]  # type: ignore[union-attr]
            ).items())),
        },
        "cases": entries,
    }
    return {"manifest": manifest, "rendered": rendered}


def write() -> None:
    built = build()
    manifest, rendered = built["manifest"], built["rendered"]
    CORPUS.mkdir(parents=True, exist_ok=True)
    for case_id, (prompt, xml) in rendered.items():  # type: ignore[union-attr]
        d = CORPUS / case_id
        d.mkdir(exist_ok=True)
        (d / "prompt.txt").write_text(prompt)
        (d / "reference.bpmn").write_text(xml)
    (CORPUS / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    counts = manifest["counts"]  # type: ignore[index]
    print(f"wrote {counts['total']} cases to {CORPUS}")  # type: ignore[index]


def verify() -> int:
    problems: list[str] = []
    built = build()
    manifest, rendered = built["manifest"], built["rendered"]

    ids = [c.id for c in ALL_CASES]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        problems.append(f"duplicate case ids: {sorted(dupes)}")
    if not 30 <= len(ALL_CASES) <= 50:
        problems.append(f"corpus must hold 30-50 pairs, has {len(ALL_CASES)}")
    hand = sum(1 for c in ALL_CASES if c.under_specified)
    if hand < 10:
        problems.append(f"need >= 10 hand-written under-specified prompts, have {hand}")

    for case in ALL_CASES:
        bad = unknown(case.expected_diagnostics)
        if bad:
            problems.append(f"{case.id}: unregistered SPEC codes {bad}")
        derived = set(derive_patterns(rendered[case.id][1]))  # type: ignore[index]
        untrue = sorted(set(case.patterns) - derived)
        if untrue:
            problems.append(
                f"{case.id}: declares pattern(s) {untrue} its reference artifact does not have"
            )

    on_disk = CORPUS / "manifest.json"
    if not on_disk.exists():
        problems.append("datasets/corpus/manifest.json is missing -- run build_corpus.py")
    else:
        if json.loads(on_disk.read_text()) != manifest:
            problems.append("manifest.json is stale -- re-run build_corpus.py")
        for case_id, (prompt, xml) in rendered.items():  # type: ignore[union-attr]
            for name, want in (("prompt.txt", prompt), ("reference.bpmn", xml)):
                p = CORPUS / case_id / name
                if not p.exists():
                    problems.append(f"missing {p.relative_to(ROOT.parent)}")
                elif p.read_text() != want:
                    problems.append(f"stale {p.relative_to(ROOT.parent)} -- re-run build_corpus.py")

    stray = {d.name for d in CORPUS.iterdir() if d.is_dir()} - set(ids) if CORPUS.exists() else set()
    if stray:
        problems.append(f"orphaned corpus directories (case removed?): {sorted(stray)}")

    if problems:
        print("corpus check FAILED:", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1

    counts = manifest["counts"]  # type: ignore[index]
    print(
        f"corpus OK: {counts['total']} pairs "  # type: ignore[index]
        f"({counts['reverse_generated']} reverse-generated, "  # type: ignore[index]
        f"{counts['hand_written_underspecified']} hand-written under-specified), "  # type: ignore[index]
        f"{len(counts['by_domain'])} domains, "  # type: ignore[index]
        f"{len(counts['by_pattern'])} structural patterns, "  # type: ignore[index]
        f"{len(SPEC_CODES)} SPEC codes registered"
    )
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify the committed corpus, write nothing")
    args = ap.parse_args()
    if args.check:
        return verify()
    write()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
